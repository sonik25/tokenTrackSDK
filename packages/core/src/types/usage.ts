/**
 * Represents a token count reported by an AI provider.
 * Counts should be non-negative integers.
 */
export type TokenCount = number;

/**
 * Additional details about input tokens.
 */
export interface InputTokenDetails {
  /** Input tokens served from cache, when reported by the provider. */
  cachedTokens?: TokenCount;

  /** Input tokens written to cache, when reported by the provider. */
  cacheWriteTokens?: TokenCount;
}

/**
 * Additional details about output tokens.
 */
export interface OutputTokenDetails {
  /** Reasoning tokens included in the output, when reported by the provider. */
  reasoningTokens?: TokenCount;
}

/**
 * Provider-independent representation of AI token usage.
 *
 * Unknown values remain undefined. They must not be assumed to be zero.
 */
export interface TokenUsage {
  /** Total input tokens consumed by the request. */
  inputTokens?: TokenCount;

  /** Total output tokens generated by the request. */
  outputTokens?: TokenCount;

  /** Total tokens, when reported by the provider. */
  totalTokens?: TokenCount;

  /** Additional input token breakdown. */
  inputTokenDetails?: InputTokenDetails;

  /** Additional output token breakdown. */
  outputTokenDetails?: OutputTokenDetails;
}
